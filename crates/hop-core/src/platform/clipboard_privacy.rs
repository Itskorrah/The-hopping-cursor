//! Respect source applications' privacy markers; never inspect content to guess secrets.
use anyhow::Result;

#[cfg(target_os = "macos")]
mod native {
    use super::*;
    use std::ffi::{c_void, CStr};
    type Id = *mut c_void;
    #[link(name = "objc")]
    extern "C" {
        fn objc_getClass(name: *const i8) -> Id;
        fn sel_registerName(name: *const i8) -> Id;
        fn objc_msgSend();
        fn objc_autoreleasePoolPush() -> Id;
        fn objc_autoreleasePoolPop(pool: Id);
    }
    struct Pool(Id);
    impl Drop for Pool {
        fn drop(&mut self) {
            unsafe { objc_autoreleasePoolPop(self.0) }
        }
    }
    unsafe fn send(object: Id, selector: &CStr) -> Id {
        let call: unsafe extern "C" fn(Id, Id) -> Id =
            std::mem::transmute(objc_msgSend as *const ());
        call(object, sel_registerName(selector.as_ptr()))
    }
    unsafe fn inspect(board: Id) -> (u64, bool) {
        let count: unsafe extern "C" fn(Id, Id) -> isize =
            std::mem::transmute(objc_msgSend as *const ());
        let revision = count(board, sel_registerName(c"changeCount".as_ptr())) as u64;
        let types = send(board, c"types");
        let string: unsafe extern "C" fn(Id, Id, *const i8) -> Id =
            std::mem::transmute(objc_msgSend as *const ());
        let contains: unsafe extern "C" fn(Id, Id, Id) -> bool =
            std::mem::transmute(objc_msgSend as *const ());
        let excluded = [
            c"org.nspasteboard.ConcealedType",
            c"org.nspasteboard.TransientType",
            c"org.nspasteboard.AutoGeneratedType",
            c"com.agilebits.onepassword",
            c"de.petermaurer.TransientPasteboardType",
            c"com.typeit4me.clipping",
            c"Pasteboard generator type",
        ]
        .iter()
        .any(|marker| {
            let name = string(
                objc_getClass(c"NSString".as_ptr()),
                sel_registerName(c"stringWithUTF8String:".as_ptr()),
                marker.as_ptr(),
            );
            contains(types, sel_registerName(c"containsObject:".as_ptr()), name)
        });
        (revision, excluded)
    }
    pub fn stamp() -> Result<(u64, bool)> {
        let _pool = Pool(unsafe { objc_autoreleasePoolPush() });
        unsafe {
            Ok(inspect(send(
                objc_getClass(c"NSPasteboard".as_ptr()),
                c"generalPasteboard",
            )))
        }
    }
    #[cfg(test)]
    mod tests {
        use super::*;
        #[test]
        fn mac_privacy_markers_on_isolated_pasteboard() {
            let _pool = Pool(unsafe { objc_autoreleasePoolPush() });
            unsafe {
                // A unique board keeps this test away from the user's clipboard.
                let board = send(
                    objc_getClass(c"NSPasteboard".as_ptr()),
                    c"pasteboardWithUniqueName",
                );
                send(board, c"clearContents");
                assert!(!inspect(board).1);
                let string: unsafe extern "C" fn(Id, Id, *const i8) -> Id =
                    std::mem::transmute(objc_msgSend as *const ());
                let marker = string(
                    objc_getClass(c"NSString".as_ptr()),
                    sel_registerName(c"stringWithUTF8String:".as_ptr()),
                    c"org.nspasteboard.ConcealedType".as_ptr(),
                );
                let empty = string(
                    objc_getClass(c"NSString".as_ptr()),
                    sel_registerName(c"stringWithUTF8String:".as_ptr()),
                    c"".as_ptr(),
                );
                let set: unsafe extern "C" fn(Id, Id, Id, Id) -> bool =
                    std::mem::transmute(objc_msgSend as *const ());
                assert!(set(
                    board,
                    sel_registerName(c"setString:forType:".as_ptr()),
                    empty,
                    marker
                ));
                assert!(inspect(board).1);
                let release: unsafe extern "C" fn(Id, Id) =
                    std::mem::transmute(objc_msgSend as *const ());
                release(board, sel_registerName(c"releaseGlobally".as_ptr()));
            }
        }
    }
}

#[cfg(target_os = "windows")]
mod native {
    use super::*;
    use windows_sys::Win32::System::{DataExchange::*, Memory::*};
    struct Open;
    impl Drop for Open {
        fn drop(&mut self) {
            unsafe {
                CloseClipboard();
            }
        }
    }
    unsafe fn format(name: &str) -> u32 {
        let name: Vec<_> = name.encode_utf16().chain([0]).collect();
        RegisterClipboardFormatW(name.as_ptr())
    }
    pub fn stamp() -> Result<(u64, bool)> {
        unsafe {
            anyhow::ensure!(
                OpenClipboard(std::ptr::null_mut()) != 0,
                "Clipboard is busy; retry"
            );
            let _open = Open;
            let excluded = format("ExcludeClipboardContentFromMonitorProcessing");
            anyhow::ensure!(excluded != 0, "Could not check clipboard privacy");
            let mut skip = IsClipboardFormatAvailable(excluded) != 0;
            for name in ["CanIncludeInClipboardHistory", "CanUploadToCloudClipboard"] {
                let id = format(name);
                anyhow::ensure!(id != 0, "Could not check clipboard privacy");
                if IsClipboardFormatAvailable(id) == 0 {
                    continue;
                }
                let data = GetClipboardData(id);
                // A malformed marker fails closed as well.
                if data.is_null() || GlobalSize(data) < 4 {
                    skip = true;
                    continue;
                }
                let pointer = GlobalLock(data) as *const u32;
                if pointer.is_null() {
                    skip = true;
                    continue;
                }
                skip |= pointer.read_unaligned() == 0;
                GlobalUnlock(data);
            }
            Ok((GetClipboardSequenceNumber() as u64, skip))
        }
    }
}
pub fn stamp() -> Result<(u64, bool)> {
    native::stamp()
}
